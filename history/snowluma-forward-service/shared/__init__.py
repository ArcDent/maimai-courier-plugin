"""共享层：插件进程与独立服务进程共用的纯类型、词汇、协议与转换（design D9）。

- 不导入 `maibot_sdk`，也不导入插件侧模块，因此无 SDK 的服务环境可直接导入；
- 插件根模块以相对导入接入同一份定义（`clock.py` / `delivery_ledger.py` /
  `forward_delivery.py` 只做重导出），不复制类型或状态机；
- 服务进程以顶层包名 `shared` 导入（仓库根在 `sys.path`），子模块相对导入与包名
  无关，两侧解析到同一份源码。

分工：`clock` 时钟；`delivery` 投递身份与账本状态；`result` 结果面与渲染；
`identifiers` 标识符规则；`mentions` 提及呈现与压平；`config_rules` 配置取值规则
（环境变量名文法与回环主机判定）；`protocol` v1 请求/响应与阶段授权；`ledger`
账本仓储协议；`send_steps` 服务端两个发送接缝。
"""

